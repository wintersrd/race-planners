def t(key: str, locale: str = DEFAULT_LOCALE, **kwargs: object) -> str:
    """Resolve a translated string by key and locale.

    Supports named placeholder interpolation via ``str.format_map``.
    Falls back to the key itself if no translation is found.
    """
    bundle = TRANSLATIONS.get(locale) or TRANSLATIONS[DEFAULT_LOCALE]
    template = bundle.get(key) or TRANSLATIONS[DEFAULT_LOCALE].get(key) or key
    if kwargs:
        return template.format_map(_SafeFormatDict(kwargs))
    return template


class _SafeFormatDict(dict[str, object]):
    """dict subclass that returns the key wrapped in braces for missing keys.

    This prevents ``str.format_map`` from raising ``KeyError`` on
    partially-populated kwargs.
    """

    def __missing__(self, key: str) -> str:
        return "{" + key + "}"
